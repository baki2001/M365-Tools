"""Plain-text report renderer (max 100 columns)."""

from __future__ import annotations

from .format import fmt_duration
from .model import Report, Section

WIDTH = 100


def _trunc(s: str, n: int) -> str:
    s = " ".join(str(s).split())
    if len(s) <= n:
        return s
    if n <= 1:
        return "…"[:n]
    keep = n - 1
    head = keep // 2
    tail = keep - head
    return s[:head] + "…" + (s[-tail:] if tail else "")


def _heading(t: str, ch: str = "=") -> list[str]:
    t = _trunc(t, WIDTH)
    return [t, ch * len(t)]


def _wrap(text: str) -> list[str]:
    import textwrap

    out: list[str] = []
    for para in text.splitlines() or [""]:
        out.extend(textwrap.wrap(para, WIDTH) or [""])
    return out


def _kv(rows: list[list[str]]) -> list[str]:
    w = min(max((len(str(r[0])) for r in rows), default=0), 30)
    return [f"{_trunc(r[0], w):<{w}}  {_trunc(r[1] if len(r) > 1 else '', WIDTH - w - 2)}" for r in rows]


def _table(cols: list[str], rows: list[list[str]]) -> list[str]:
    n = len(cols)
    if n == 0:
        return []
    cells = [[str(c) for c in r] + [""] * (n - len(r)) for r in rows]
    nat = [max([len(cols[i])] + [len(r[i]) for r in cells]) for i in range(n)]
    avail = WIDTH - 2 * (n - 1)
    widths = nat[:]
    while sum(widths) > avail:
        i = max(range(n), key=lambda k: widths[k])
        if widths[i] <= 4:
            break
        widths[i] -= 1
    def line(vals: list[str]) -> str:
        return "  ".join(f"{_trunc(v, widths[i]):<{widths[i]}}" for i, v in enumerate(vals)).rstrip()
    out = [line(cols), "  ".join("-" * w for w in widths)]
    out += [line(r) for r in cells]
    return out


def _section(s: Section) -> list[str]:
    out = _heading(s.title, "-")
    if s.note:
        out += _wrap(s.note)
    if s.kind == "kv":
        out += _kv(s.rows)
    elif s.kind == "table":
        out += _table(s.columns, s.rows) if s.rows else ["(none)"]
    else:
        out += _wrap(s.text)
    return out


def render_text(report: Report) -> str:
    lines = _heading(report.title)
    lines += [
        f"Mode:        {report.mode}",
        f"Source:      {_trunc(report.source, WIDTH - 13)}",
        f"Destination: {_trunc(report.destination, WIDTH - 13)}",
        f"Started:     {report.started:%Y-%m-%d %H:%M:%S}",
        f"Finished:    {report.finished:%Y-%m-%d %H:%M:%S}"
        + f"  ({fmt_duration((report.finished - report.started).total_seconds())})",
        "",
    ]
    if report.summary:
        lines += _heading("Summary") + _kv([[k, v] for k, v in report.summary]) + [""]
    for s in report.sections:
        lines += _section(s) + [""]
    if report.not_migrated:
        lines += _heading("What was NOT migrated", "-")
        for item in report.not_migrated:
            lines += [("- " + ln if i == 0 else "  " + ln) for i, ln in enumerate(_wrap_w(item, WIDTH - 2))]
        lines.append("")
    if report.footer:
        lines += _wrap(report.footer)
    lines.append("Generated by m365tools spmig")
    return "\n".join(lines) + "\n"


def _wrap_w(text: str, w: int) -> list[str]:
    import textwrap

    return textwrap.wrap(text, w) or [""]
